/** Reverse lookup: IATA -> airport (for displaying a cookie-stored origin). */
export const IATA_ORIGIN: Record<string, OriginAirport> = {};
for (const o of Object.values(COUNTRY_ORIGIN)) IATA_ORIGIN[o.iata] = o;

const FALLBACK = { iata: 'YUL', city: 'Montreal', cityFr: 'Montréal', latitude: 45.4678, longitude: -73.7423 };

/** Resolve a visitor's origin airport: saved choice, then Cloudflare country, then YUL. */
export function resolveOrigin(cookieIata: string | null | undefined, cfCountry: string | null | undefined): OriginAirport {
  const cookieHit = cookieIata ? IATA_ORIGIN[cookieIata.toUpperCase()] : undefined;
  if (cookieHit) return cookieHit;
  const countryHit = cfCountry ? COUNTRY_ORIGIN[cfCountry.toUpperCase()] : undefined;
  if (countryHit) return countryHit;
  return FALLBACK;
}
